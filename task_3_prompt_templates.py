
#!/usr/bin/env python3

"""
Task 3: Prompt Templates — Dynamic, Reusable Prompts

Goal:
Learn how to create a reusable prompt instead of hardcoding
a different prompt for every request.
"""

import os
from dotenv import load_dotenv

# PromptTemplate is a LangChain class that lets us define a prompt
# containing placeholders, such as {topic} and {style}.
# We can fill those placeholders with different values whenever needed.
from langchain_core.prompts import PromptTemplate

# ChatOpenAI is LangChain's wrapper around chat models that expose
# an OpenAI-compatible API. It provides a consistent .invoke() interface.
from langchain_openai import ChatOpenAI


# Load variables from the project's .env file into the environment.
# This allows os.getenv() to read OPENAI_API_KEY and OPENAI_API_BASE.
# The API key stays outside the source code instead of being hardcoded.
load_dotenv()


def main():
    print("🎯 Task 3: Prompt Templates")
    print("=" * 50)

    # ---------------------------------------------------------
    # STEP 1: CREATE A REUSABLE PROMPT TEMPLATE
    # ---------------------------------------------------------

    # Without a template, we might hardcode a new string every time:
    # "Explain artificial intelligence in exactly 5 words"
    #
    # A template separates the fixed structure from changing values.
    # {topic} and {style} are placeholders that we will fill later.
    template = PromptTemplate(
        input_variables=["topic", "style"],  # Names of required placeholders.
        template="Explain {topic} in {style}"  # Reusable prompt structure.
    )

    # input_variables tells LangChain which values the template expects.
    # If we forget a required value when formatting, we'll get an error.
    #
    # Example:
    # topic = "artificial intelligence"
    # style = "exactly 5 words"
    #
    # Formatted result:
    # "Explain artificial intelligence in exactly 5 words"

    # ---------------------------------------------------------
    # STEP 2: INITIALIZE THE LANGUAGE MODEL
    # ---------------------------------------------------------

    llm = ChatOpenAI(
        model="gpt-5.6-luna",  # Model identifier supported by our API endpoint.

        # Read credentials from environment variables rather than
        # putting secret values directly in the Python source code.
        api_key=os.getenv("OPENAI_API_KEY"),
        base_url=os.getenv("OPENAI_API_BASE"),

        # temperature controls the randomness of model generation.
        # Lower values generally produce more predictable responses.
        # Higher values generally allow more varied responses.
        # 0.7 is a moderate setting; it does NOT guarantee correctness
        # or enforce an exact number of words.
        temperature=0.7
    )

    # We create the model object here but have not called the API yet.
    # The actual model request happens when we call llm.invoke() below.

    # ---------------------------------------------------------
    # STEP 3: FILL IN THE TEMPLATE
    # ---------------------------------------------------------

    # .format() substitutes the placeholder values into the template.
    # This step creates a normal string; it does NOT call the AI.
    prompt = template.format(
        topic="artificial intelligence",  # Replaces {topic}.
        style="exactly 5 words"           # Replaces {style}.
    )

    print(f"\nFormatted prompt: {prompt}")

    # We can reuse the same template with different values:
    #
    # another_prompt = template.format(
    #     topic="cloud computing",
    #     style="a simple explanation for beginners"
    # )
    #
    # The template stays the same; only the input values change.

    # ---------------------------------------------------------
    # STEP 4: SEND THE PROMPT TO THE MODEL
    # ---------------------------------------------------------

    # .invoke() sends the prompt to the configured model and waits
    # for its response. This is the point where the API is called.
    response = llm.invoke(prompt)

    # LangChain returns an AIMessage object, not just a plain string.
    # .content extracts the text generated by the model.
    print(f"\nAI response: {response.content}")

    # Remember the distinction:
    # template.format(...) -> builds the prompt string locally.
    # llm.invoke(prompt)    -> calls the model.
    # response.content     -> extracts the generated text.

    # ---------------------------------------------------------
    # STEP 5: CREATE THE COMPLETION MARKER
    # ---------------------------------------------------------

    # The course uses marker files to track completed exercises.
    # We use a local "markers" directory instead of /root/markers,
    # because this project is running on our Mac.
    os.makedirs("markers", exist_ok=True)

    # exist_ok=True means Python won't fail if the directory already exists.
    # The "w" mode creates the file or overwrites its previous contents.
    with open("markers/task3_complete.txt", "w") as file:
        file.write("COMPLETED")

    print("\n✅ Task 3 completed!")


# __name__ is set to "__main__" when this file is run directly.
# This guard prevents main() from running automatically if another
# Python file imports this module.
if __name__ == "__main__":
    main()
